#!/usr/bin/env python3
"""Generates app/assets/css/dark-compat.css.

Many screens use LIGHT-ONLY Tailwind palette classes (bg-emerald-100 text-emerald-800 …) for badges, alerts and
tables. In dark mode those become pale boxes with pale text. Instead of adding `dark:` variants to every component,
this file re-maps those classes ONCE, from the palette itself:
    bg-{c}-{50|100|200}     -> a translucent tint of {c}-500 over the page background
    text-{c}-{600..950}     -> {c}-300   (neutrals -> the foreground / muted-foreground tokens)
    border-{c}-{100..300}   -> a translucent {c}-500   (neutrals -> --border)
    hover:bg-{c}-{50..200}  -> a slightly stronger tint
An element that already has its own `dark:bg-*` / `dark:text-*` / `dark:border-*` class is left alone (:not guard).
Re-run after changing the rules:  python3 scripts/gen-dark-compat.py
"""
import pathlib

COLORS = "red orange amber yellow lime green emerald teal cyan sky blue indigo violet purple fuchsia pink rose".split()
NEUTRALS = "slate gray zinc neutral stone".split()
OUT = pathlib.Path(__file__).resolve().parent.parent / "app/assets/css/dark-compat.css"

tint = lambda c, pct: f"color-mix(in oklab, var(--color-{c}-500) {pct}%, var(--background))"
alpha = lambda c, pct: f"color-mix(in oklab, var(--color-{c}-500) {pct}%, transparent)"

L = ["/* GENERATED by scripts/gen-dark-compat.py — do not edit by hand. Dark-mode mapping of light-only palette classes. */",
     "/* Not in a @layer on purpose: it must win over the utilities layer without !important. */", ""]
G_BG, G_TX, G_BD = ':not([class*="dark:bg-"])', ':not([class*="dark:text-"])', ':not([class*="dark:border-"])'


def rule(sel, decl):
    L.append(f"{sel} {{ {decl} }}")


for c in COLORS + NEUTRALS:
    neutral = c in NEUTRALS
    for s in (50, 100, 200):
        bg = f"background-color: {tint(c, 14 if s < 200 else 20)};"
        rule(f".dark .bg-{c}-{s}{G_BG}", bg)
        rule(f'.dark [class^="bg-{c}-{s}/"]{G_BG}, .dark [class*=" bg-{c}-{s}/"]{G_BG}', bg)
        rule(f".dark .hover\\:bg-{c}-{s}:hover{G_BG}", f"background-color: {tint(c, 22)};")
    for s in (600, 700, 800, 900, 950):
        col = (("var(--muted-foreground)" if s <= 700 else "var(--foreground)") if neutral else f"var(--color-{c}-300)")
        rule(f".dark .text-{c}-{s}{G_TX}", f"color: {col};")
    for s in (100, 200, 300):
        rule(f".dark .border-{c}-{s}{G_BD}", f"border-color: {'var(--border)' if neutral else alpha(c, 40)};")

rule(".dark .bg-white" + G_BG, "background-color: var(--card);")
rule(".dark .bg-white\\/10" + G_BG, "background-color: color-mix(in oklab, var(--foreground) 10%, transparent);")
OUT.write_text("\n".join(L) + "\n")
print("wrote", OUT, len(L), "rules")
